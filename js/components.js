let cloudSeed = 7;
function cloudRnd(a = 0, b = 1) { cloudSeed = (cloudSeed * 16807) % 2147483647; return a + (b - a) * (cloudSeed / 2147483647); }
function puff(parent, x, y, w, h, top, bottom) {
  const g = el('g', { transform: `translate(${x} ${y})` }, parent);
  const lobes = 3 + Math.floor(w / 70);
  for (let k = 0; k < lobes; k++) {
    const lx = (k / (lobes - 1) - .5) * w * .8;
    el('ellipse', { cx: lx, cy: -cloudRnd(0, h * .45), rx: w / lobes * cloudRnd(.8, 1.2), ry: h * cloudRnd(.6, 1), fill: top }, g);
  }
  el('ellipse', { cx: 0, cy: h * .35, rx: w * .46, ry: h * .3, fill: bottom, opacity: .8 }, g);
  el('ellipse', { cx: -w * .12, cy: -h * .8, rx: w * .3, ry: h * .28, fill: '#fff', opacity: .55 }, g);
  return g;
}
