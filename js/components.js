// ---------- CLOUDS: the four V1 families, reconstructed from the documented spec ----------
// PORTED VERBATIM from catalog_final_optimized_v3.html (a previous, more
// complete catalog build the user had) -- exact puff() geometry, exact
// seasonal opacity gates, and the real requestAnimationFrame drift loop.
// My earlier version of this file was a from-memory RECONSTRUCTION with no
// animation loop at all, which is why those clouds never moved -- this
// replaces it with the actual working implementation instead of guessing
// again.
let cloudSeed = 7;
function cloudRnd(a = 0, b = 1) { cloudSeed = (cloudSeed * 16807) % 2147483647; return a + (b - a) * (cloudSeed / 2147483647); }
function puff(parent, x, y, w, h, top, bottom) {
  const g = el('g', { transform: `translate(${x} ${y})` }, parent);
  const lobes = 3 + Math.floor(w / 70);
  for (let k = 0; k < lobes; k++) {
    const lx = (k / (lobes - 1) - .5) * w * .8;
    el('ellipse', { cx: lx, cy: -cloudRnd(0, h * .45), rx: w / lobes * cloudRnd(.8, 1.2), ry: h * cloudRnd(.6, 1), fill: top }, g);
  }
  el('ellipse', { cx: 0, cy: h * .35, rx: w * .46, ry: h * .3, fill: bottom, opacity: .8 }, g);
  el('ellipse', { cx: -w * .12, cy: -h * .8, rx: w * .3, ry: h * .28, fill: '#fff', opacity: .55 }, g);
  return g;
}
const CLOUD_GATES = {
  cumulus:      [.9, .2, .7, .25],   // winter, spring, summer, fall
  cirrus:       [.8, .6, .1, .9],
  altocumulus:  [.1, .9, .2, .7],
  cumulonimbus: [0,  .1, .9, .15],
};
const CLOUD_SEASON_IDX = { winter: 0, spring: 1, summer: 2, fall: 3 };
const CLOUD_VIEWBOX = {
  cumulus: '0 0 1600 320', cirrus: '0 0 1600 220',
  altocumulus: '0 0 1600 260', cumulonimbus: '0 0 1000 400',
};
const CLOUD_BUILDERS = {
  cumulus(svg) {
    const g = el('g', {}, svg);
    for (let i = 0; i < 5; i++) puff(g, cloudRnd(100, 1400), cloudRnd(120, 230), cloudRnd(150, 300), cloudRnd(28, 46), '#eae6f3', '#b7aed0');
    return g;
  },
  cirrus(svg) {
    const g = el('g', {}, svg);
    for (let i = 0; i < 7; i++) {
      const x = cloudRnd(0, 1200), y = cloudRnd(30, 150), w = cloudRnd(200, 460);
      el('path', { d: `M${x} ${y} q ${w*.3} -${cloudRnd(8,18)} ${w*.6} -4 q ${w*.2} 2 ${w*.4} -${cloudRnd(4,10)} q -${w*.25} 12 -${w*.55} 8 q -${w*.25} 6 -${w*.45} -4 Z`, fill: '#f3f0fa', opacity: cloudRnd(.4, .75) }, g);
    }
    return g;
  },
  altocumulus(svg) {
    const g = el('g', {}, svg);
    for (let i = 0; i < 2; i++) {
      const y = cloudRnd(80, 160), x0 = cloudRnd(50, 400);
      for (let k = 0; k < 8; k++) puff(g, x0 + k * cloudRnd(70, 95), y + cloudRnd(-10, 10), cloudRnd(50, 80), cloudRnd(12, 18), '#efeaf6', '#c3b9d9');
    }
    return g;
  },
  cumulonimbus(svg) {
    const g = el('g', {}, svg);
    const x = 500, base = 340;
    for (let k = 0; k < 6; k++) puff(g, x + cloudRnd(-60, 60), base - k * 34, 220 - k * 22, 34, k > 3 ? '#f4f1f8' : '#e2ddee', '#a89ec4');
    el('path', { d: `M${x-200} ${base-210} q 120 -30 300 -24 q 100 4 200 -18 q -110 40 -280 42 q -140 4 -220 0 Z`, fill: '#f4f1f8', opacity: .9 }, g);
    return g;
  },
};

// Builds a cloud family directly into the given <svg> (must already have its
// viewBox set to CLOUD_VIEWBOX[family]) and returns { g, stopDrift } -- call
// stopDrift() before rebuilding/discarding the svg to avoid leaking the
// rAF loop, since this animates continuously rather than on a per-render basis.
function buildCloudFamily(family, svg, season, getWind) {
  const g = CLOUD_BUILDERS[family](svg);
  g.setAttribute('opacity', CLOUD_GATES[family][CLOUD_SEASON_IDX[season] ?? 2]);
  const vbW = parseFloat(svg.getAttribute('viewBox').split(' ')[2]);
  const wrap = vbW + 400;
  let raf;
  function tick(ts) {
    const t = ts / 1000;
    const w = getWind ? getWind() : 1;
    const speed = 8 + w * 6;
    Array.from(g.children).forEach((child, i) => {
      if (!child.dataset.phase) {
        const m = (child.getAttribute('transform') || '').match(/translate\(([-\d.]+)[ ,]+([-\d.]+)\)/);
        const ox = m ? parseFloat(m[1]) : (i / Math.max(1, g.children.length)) * wrap;
        child.dataset.oy = m ? m[2] : '0';
        child.dataset.phase = String(((ox % wrap) + wrap) % wrap);
      }
      const phase = parseFloat(child.dataset.phase);
      const drift = ((t * speed + phase) % wrap) - 200;
      child.setAttribute('transform', 'translate(' + drift.toFixed(0) + ' ' + child.dataset.oy + ')');
    });
    raf = requestAnimationFrame(tick);
  }
  raf = requestAnimationFrame(tick);
  return { g, stopDrift: () => cancelAnimationFrame(raf) };
}

